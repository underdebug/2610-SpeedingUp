"""Create lower resolution rigid body parts. Requires numpy; originals stay intact."""
from pathlib import Path
import argparse
import numpy as np


def simplify(vertices, faces, ratio=0.25):
    target = int(len(faces) * ratio)
    quadrics = np.zeros((len(vertices), 4, 4))
    triangles = vertices[faces]
    normals = np.cross(triangles[:, 1] - triangles[:, 0], triangles[:, 2] - triangles[:, 0])
    normals /= np.linalg.norm(normals, axis=1)[:, None]
    planes = np.column_stack((normals, -np.sum(normals * triangles[:, 0], axis=1)))
    for corner in range(3):
        np.add.at(quadrics, faces[:, corner], planes[:, :, None] * planes[:, None, :])
    while len(faces) > target:
        edges, counts = np.unique(np.sort(np.concatenate([faces[:, [0, 1]], faces[:, [1, 2]], faces[:, [2, 0]]]), axis=1), axis=0, return_counts=True)
        boundary = set(edges[counts == 1].ravel())
        incident = [set() for _ in vertices]
        neighbors = [set() for _ in vertices]
        for i, face in enumerate(faces):
            for v in face:
                incident[v].add(i)
                neighbors[v].update(int(w) for w in face if w != v)
        mids = (vertices[edges[:, 0]] + vertices[edges[:, 1]]) / 2
        homogeneous = np.column_stack((mids, np.ones(len(mids))))
        costs = np.einsum('bi,bij,bj->b', homogeneous, quadrics[edges[:, 0]] + quadrics[edges[:, 1]], homogeneous)
        blocked = set()
        mapping = np.arange(len(vertices))
        collapsed = 0
        for idx in np.argsort(costs):
            a, b = map(int, edges[idx])
            if a in blocked or b in blocked or a in boundary or b in boundary or counts[idx] != 2:
                continue
            shared = incident[a] & incident[b]
            opposite = set(faces[list(shared)].ravel()) - {a, b}
            if neighbors[a] & neighbors[b] != opposite:
                continue
            affected = sorted((incident[a] | incident[b]) - shared)
            # Tiny closed components can satisfy the link check yet collapse
            # into two coincident triangles. Keep distinct surviving faces.
            surviving = faces[affected].copy()
            surviving[surviving == b] = a
            canonical = np.sort(surviving, axis=1)
            if len(np.unique(canonical, axis=0)) != len(canonical):
                continue
            old = vertices[faces[affected]]
            new = old.copy()
            new[(faces[affected] == a) | (faces[affected] == b)] = mids[idx]
            n0 = np.cross(old[:, 1] - old[:, 0], old[:, 2] - old[:, 0])
            n1 = np.cross(new[:, 1] - new[:, 0], new[:, 2] - new[:, 0])
            if np.any(np.sum(n0 * n1, axis=1) <= 0.2 * np.linalg.norm(n0, axis=1) * np.linalg.norm(n1, axis=1)) or np.any(np.linalg.norm(n1, axis=1) < 1e-12):
                continue
            vertices[a] = mids[idx]
            quadrics[a] += quadrics[b]
            mapping[b] = a
            blocked.update(neighbors[a] | neighbors[b] | {a, b})
            collapsed += 1
            if len(faces) - 2 * collapsed <= target:
                break
        if not collapsed:
            break
        faces = mapping[faces]
        faces = faces[(faces[:, 0] != faces[:, 1]) & (faces[:, 1] != faces[:, 2]) & (faces[:, 2] != faces[:, 0])]
    used, inverse = np.unique(faces, return_inverse=True)
    return vertices[used], inverse.reshape(-1, 3)


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', default='meshes/female')
    parser.add_argument('--destination', default='meshes/female-low')
    parser.add_argument('--ratio', type=float, default=0.25)
    args = parser.parse_args()
    if not 0 < args.ratio < 1:
        parser.error('--ratio must be between 0 and 1')
    source_dir = root / args.source
    destination = root / args.destination
    if source_dir.resolve() == destination.resolve():
        parser.error('source and destination must differ')
    destination.mkdir(exist_ok=True)
    total_before = total_after = 0
    for source in sorted(source_dir.glob('body*.obj')):
        vertices, faces = [], []
        for line in source.read_text().splitlines():
            parts = line.split()
            if parts and parts[0] == 'v':
                vertices.append([float(x) for x in parts[1:4]])
            elif parts and parts[0] == 'f':
                polygon = [int(x.split('/')[0]) - 1 for x in parts[1:]]
                for i in range(1, len(polygon) - 1):
                    faces.append([polygon[0], polygon[i], polygon[i + 1]])
        before = len(faces)
        vertices, faces = simplify(np.array(vertices), np.array(faces), args.ratio)
        with (destination / source.name).open('w') as out:
            out.write('# Simplified rigid body part; generated by scripts/simplify_body.py\n')
            for v in vertices:
                out.write('v ' + ' '.join(f'{x:.9g}' for x in v) + '\n')
            for f in faces:
                out.write('f ' + ' '.join(str(x + 1) for x in f) + '\n')
        print(f'{source.name}: {before} -> {len(faces)} triangles', flush=True)
        total_before += before
        total_after += len(faces)
    print(f'Total: {total_before} -> {total_after} triangles')


if __name__ == '__main__':
    main()
